class TestBranchToIssueNumber(unittest.TestCase):
    def test_matches(self):
        self.assertEqual(branch_to_issue_number("sf_businesscapability-42"), 42)

    def test_feature_prefix(self):
        self.assertEqual(branch_to_issue_number("feature/sf_businesscapability-22"), 22)

    def test_no_match_main(self):
        self.assertIsNone(branch_to_issue_number("main"))

    def test_no_match_random(self):
        self.assertIsNone(branch_to_issue_number("random-branch"))


class TestAggregate(unittest.TestCase):
    def _row(self, branch, cost):
        return {"git_branch": branch, "total_cost_usd": cost}

    def test_sum_clean(self):
        rows = [self._row("main", "1.00"), self._row("main", "2.50")]
        result = aggregate(rows)
        self.assertAlmostEqual(result["main"]["cost_sum"], 3.50)
        self.assertEqual(result["main"]["n_errors"], 0)

    def test_excludes_error(self):
        rows = [self._row("main", "5.00"), self._row("main", "ERROR")]
        result = aggregate(rows)
        self.assertAlmostEqual(result["main"]["cost_sum"], 5.00)
        self.assertEqual(result["main"]["n_errors"], 1)
        self.assertEqual(result["main"]["n_sessions"], 2)

    def test_all_error(self):
        rows = [self._row("main", "ERROR"), self._row("main", "ERROR")]
        result = aggregate(rows)
        self.assertAlmostEqual(result["main"]["cost_sum"], 0.0)
        self.assertEqual(result["main"]["n_errors"], 2)
        self.assertEqual(result["main"]["n_sessions"], 2)

    def test_empty_branch(self):
        rows = [{"git_branch": "", "total_cost_usd": "1.00"}]
        result = aggregate(rows)
        self.assertIn("(no branch)", result)


